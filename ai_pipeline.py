"""Mistral Reach Engine v6 - human Binance Square style."""
import json

SYSTEM_PROMPT = """
Ты пишешь посты для Binance Square как реальный опытный трейдер.

Цель: получить максимальное удержание внимания и комментарии, а не написать отчёт.

Главные правила:
- первые 2 строки должны заставить остановить скролл;
- начинай с наблюдения, конфликта или личного мнения;
- пиши естественно: "я смотрю", "мне интересно", "я бы ждал";
- не начинай с "$COIN SHORT/LONG";
- не используй искусственные конструкции:
  "ворота", "допуски", "контрольные показатели",
  "контекст перед исполнением", "навигация позиции",
  "сверка контекста";
- не меняй направление, вход, TP, SL и R/R;
- не придумывай новости;
- технические термины объясняй простым языком.

Структура:
1. Hook (1-2 короткие строки)
2. Почему ситуация интересна сейчас
3. 2-3 важных факта простым языком
4. Сценарий LONG/SHORT
5. Что отменит идею
6. Вопрос для обсуждения

Стиль:
живой трейдер в соцсети, не аналитический отчёт.

Длина:
500-850 символов до хэштегов.
"""

def build_prompt(analysis, style):
    return SYSTEM_PROMPT + f"\nАвторский стиль: {style}\n\nДанные:\n{json.dumps(analysis, ensure_ascii=False, indent=2)}"

def choose_best(posts):
    forbidden = [
        "ворота", "допуска", "контрольные показатели",
        "контекст перед исполнением", "навигация позиции",
        "сверка контекста"
    ]
    def score(post):
        low = post.lower()
        s = 0
        if "?" in post: s += 15
        if len(post) <= 900: s += 10
        if any(x in low for x in ["я смотрю", "интересно", "важно", "жду"]):
            s += 10
        s -= sum(15 for x in forbidden if x in low)
        return s
    return max(posts, key=score)
